/**
 * 街角家具（店外那一圈日式日常件，全部摆在 10×10 底座的人行道与车行道边上）。
 * 清单按需求给全：自动贩卖机×2、自行车、雨伞架、垃圾桶、公告栏、空调外机、
 * 电线杆+横担+绝缘子+变压器+电线、路灯、路牌、信号灯杆、街角护栏（在 store.ts）、
 * 湿反光水洼（glow 长条，夜里灯一照就是一条倒影）。
 */
import { C, R90 } from './palette.js';
import { B } from './store.js';
import type { Diorama } from './kit.js';

/** 门/信号灯/雨痕/滴水的局部锚点：动画层按这些点换算到世界坐标（见 konbiniProps.ts） */
export const ANCHOR = {
  /** 自动门两扇的关门位（局部坐标，南立面 z=B.z1 那面；开门时各自往两侧滑） */
  doorL: { x: 0.30, y: 1.19, z: 1.03 }, doorR: { x: 1.15, y: 1.19, z: 1.03 },
  /** 信号灯三盏 */
  lamp: { x: 3.52, y: 3.24, z: 3.42 },
  /** 屋檐滴水点（雨棚外沿） */
  drip: [[-3.4, 2.6, 2.05], [-0.6, 2.6, 2.05], [1.9, 2.6, 2.05], [2.6, 2.6, 0.4], [2.6, 2.6, -1.6]] as const,
  /** 玻璃上的雨痕起点（橱窗） */
  run: [[-3.36, 2.4, 1.06], [-2.08, 2.4, 1.06], [-0.8, 2.4, 1.06], [1.86, 2.3, -2.0], [1.86, 2.3, -0.8]] as const,
  /** 地面积水涟漪发射点（人行道/车行道/巷口） */
  pool: [[0.7, 0.06, 2.4], [-2.4, 0.06, 2.6], [2.6, 0.06, 2.0], [4.1, 0.06, 0.6], [3.6, 0.06, -3.2], [-3.0, 0.06, 4.2]] as const,
};

export function buildStreetProps(d: Diorama): void {
  // ---------- 自动贩卖机两台（东墙外，正面朝路，发光面是夜里最亮的一块） ----------
  for (let i = 0; i < 2; i++) {
    const z = -1.7 + i * 1.25;
    d.box('body', 0.56, 1.92, 1.05, 2.36, 0.96, z, i ? '#c9cdd8' : '#d3c8c8');
    d.box('body', 0.58, 0.1, 1.07, 2.36, 1.94, z, C.frame);
    d.quad('glow', 0.92, 1.44, 2.65, 1.06, z, i ? '#bfe6ff' : '#ffd9c4', { ry: R90 });
    for (let k = 0; k < 3; k++) for (let j = 0; j < 4; j++) {
      d.box('glow', 0.06, 0.16, 0.14, 2.68, 0.62 + k * 0.42, z - 0.33 + j * 0.22, ['#e8604f', '#4f9ee8', '#f0c33c', '#66c07a'][(k + j) % 4]);
    }
    d.box('body', 0.2, 0.3, 0.4, 2.5, 0.3, z + 0.3, C.frame);                     // 取物口
    d.slab('glow', 0.1, 0.3, 2.62, 0.32, z + 0.3, C.neonA);
  }

  // ---------- 自行车（两只轮 + 斜梁 + 前车筐，停在店门口） ----------
  const bx = 2.55, bz = 1.75, ry = -0.4;
  const rot = (lx: number, lz: number): [number, number] => [bx + lx * Math.cos(ry) + lz * Math.sin(ry), bz - lx * Math.sin(ry) + lz * Math.cos(ry)];
  const [wx1, wz1] = rot(-0.45, 0), [wx2, wz2] = rot(0.45, 0);
  d.cyl('body', 0.03, 0.03, 0.06, 10, wx1, 0.34, wz1, C.frame, { rz: R90 });
  d.cyl('body', 0.32, 0.32, 0.05, 12, wx1, 0.34, wz1, '#2f3644', { rz: R90 });
  d.cyl('body', 0.32, 0.32, 0.05, 12, wx2, 0.34, wz2, '#2f3644', { rz: R90 });
  d.box('body', 0.05, 0.05, 0.9, (wx1 + wx2) / 2, 0.62, (wz1 + wz2) / 2, '#b8443c', { ry });
  d.strut('body', wx1, 0.36, wz1, bx - 0.05, 0.78, bz, 0.025, '#c9ced8');
  d.strut('body', wx2, 0.36, wz2, bx - 0.05, 0.78, bz, 0.025, '#c9ced8');
  d.strut('body', wx2, 0.36, wz2, bx + 0.42, 0.86, bz, 0.025, '#c9ced8');
  d.box('body', 0.24, 0.04, 0.1, bx - 0.06, 0.86, bz, C.frame);                   // 座垫
  d.box('body', 0.06, 0.34, 0.06, bx + 0.42, 0.9, bz, '#c9ced8');                 // 立把
  d.box('body', 0.22, 0.16, 0.2, bx + 0.5, 0.78, bz, '#8e97a6');                  // 车筐

  // ---------- 雨伞架 + 垃圾桶 + 公告栏 ----------
  d.cyl('body', 0.2, 0.24, 0.46, 8, -0.75, 0.23, 1.5, '#5b6472');
  for (let i = 0; i < 3; i++) {
    d.strut('body', -0.75, 0.44, 1.5, -0.95 + i * 0.2, 1.34, 1.62, 0.028, ['#d9534f', '#3f7fbf', '#f0c33c'][i]);
    d.cyl('body', 0.05, 0.02, 0.1, 6, -0.95 + i * 0.2, 1.36, 1.62, ['#d9534f', '#3f7fbf', '#f0c33c'][i]);
  }
  for (let i = 0; i < 2; i++) {
    d.box('body', 0.44, 0.66, 0.34, -1.75 + i * 0.5, 0.33, 1.55, i ? '#4f7a52' : '#3f6f9e');
    d.box('body', 0.46, 0.08, 0.36, -1.75 + i * 0.5, 0.68, 1.55, C.frame);
    d.slab('body', 0.2, 0.14, -1.75 + i * 0.5, 0.72, 1.55, '#c9ced8');
  }
  d.box('body', 1.1, 1.5, 0.12, -3.5, 1.5, B.z1 + 0.14, C.frame);                 // 公告栏
  d.box('body', 1.24, 0.12, 0.28, -3.5, 2.32, B.z1 + 0.16, C.roof);
  for (let i = 0; i < 3; i++) d.quad('glow', 0.3, 0.42, -3.82 + i * 0.32, 1.7 - (i % 2) * 0.34, B.z1 + 0.21, [C.warm, C.neonB, C.coolWhite][i]);

  // ---------- 空调外机（东墙高处）+ 落水管 ----------
  d.box('body', 0.36, 0.62, 0.9, B.x1 + 0.24, 2.3, -0.4, '#aab2bd');
  d.cyl('body', 0.24, 0.24, 0.06, 12, B.x1 + 0.44, 2.3, -0.4, C.frame, { rz: R90 });
  d.strut('body', B.x1 + 0.24, 1.98, -0.75, B.x1 + 0.06, 1.7, -0.75, 0.03, C.metal);
  d.cyl('body', 0.06, 0.06, 2.2, 6, B.x1 + 0.1, 1.1, 0.75, '#98a1ad');
  d.cyl('body', 0.07, 0.07, 3.2, 6, B.x0 - 0.12, 1.6, -1.2, '#98a1ad');

  // ---------- 电线杆（路口那根，横担+绝缘子+变压器+拉线）与三根电线 ----------
  const px = 3.4, pz = 2.5;
  d.cyl('body', 0.13, 0.18, 7.2, 8, px, 3.6, pz, '#8f958f');
  d.box('body', 0.1, 0.1, 1.7, px, 6.5, pz, '#7a7f78');
  d.box('body', 0.1, 0.1, 1.1, px, 5.9, pz, '#7a7f78');
  for (let i = 0; i < 3; i++) d.cyl('body', 0.05, 0.05, 0.16, 6, px, 6.6, pz - 0.6 + i * 0.6, '#c9ced8');
  d.cyl('body', 0.2, 0.2, 0.5, 8, px + 0.25, 5.2, pz, '#6f7681');                 // 变压器
  d.box('body', 0.3, 0.42, 0.06, px, 1.6, pz - 0.2, '#c9ced8');                   // 杆上小牌
  d.strut('body', px, 6.5, pz - 0.6, B.x1 + 0.2, 3.5, B.z1 + 0.2, 0.02, '#1e232c');
  d.strut('body', px, 6.5, pz + 0.5, px + 1.5, 5.4, pz + 4.6, 0.02, '#1e232c');
  d.strut('body', px, 6.0, pz - 0.5, B.x0, 3.6, B.z0, 0.02, '#1e232c');

  // ---------- 路灯（暖光头 + 地面一条湿反光，夜里最常见的动画语言） ----------
  const lx = -2.3, lz = 2.85;
  d.cyl('body', 0.07, 0.1, 4.3, 8, lx, 2.15, lz, '#6f7681');
  d.box('body', 0.08, 0.08, 0.6, lx, 4.28, lz + 0.3, '#6f7681');
  d.box('body', 0.34, 0.12, 0.5, lx, 4.2, lz + 0.6, '#4c535e');
  d.slab('glow', 0.3, 0.42, lx, 4.12, lz + 0.6, '#e8f6ff');                 // 冷白光，与新加的路灯同一色温
  d.quad('glow', 0.5, 3.4, lx, 0.055, lz + 2.0, '#4a4331', { rx: -R90 });
  for (const [sx, sz] of [[0.7, 2.4], [-2.4, 2.6], [2.6, 2.0]] as const) {
    d.quad('glow', 0.4, 1.5, sx, 0.052, sz + 0.6, '#3f3a2c', { rx: -R90 });       // 别处的水洼反光条
  }

  // ---------- 路牌 + 信号灯杆（三盏灯是动画层，这里只给箱子与横臂） ----------
  d.cyl('body', 0.06, 0.08, 2.6, 6, 2.95, 1.3, 1.5, '#7f868f');
  d.box('body', 0.5, 0.3, 0.05, 2.95, 2.5, 1.5, '#3f6f9e');
  d.box('glow', 0.42, 0.22, 0.02, 2.95, 2.5, 1.53, '#dfe8f0');
  d.cyl('body', 0.08, 0.1, 3.4, 6, ANCHOR.lamp.x, 1.7, ANCHOR.lamp.z, '#5a6068');
  d.box('body', 0.5, 0.08, 0.08, ANCHOR.lamp.x - 0.2, 3.3, ANCHOR.lamp.z, '#5a6068');
  d.box('body', 0.2, 0.66, 0.16, ANCHOR.lamp.x, ANCHOR.lamp.y, ANCHOR.lamp.z, C.frame);
  d.box('body', 0.24, 0.1, 0.2, ANCHOR.lamp.x, ANCHOR.lamp.y + 0.4, ANCHOR.lamp.z, '#4c535e');
}
