/**
 * 便利店内部陈设（全部走 glow 自发光桶 ⇒ 夜里从外面看就是「灯全开、暖、满」，
 * 不需要额外光源，也不受局内那套白天灯光影响；室外冷暗与室内暖亮就这样拉开）。
 * 可见清单按需求逐项给到：货架、饮料柜、便当区、饭团零食、收银台、咖啡机、杂志架、
 * 海报、店内灯箱、冰柜、关东煮柜台、地面导视、储物柜与后场门。
 */
import { C, R90 } from './palette.js';
import { B } from './store.js';
import type { Diorama } from './kit.js';

const PROD = [C.prod1, C.prod2, C.prod3, C.prod4, C.prod5];

export function buildStoreInterior(d: Diorama): void {
  const X0 = B.x0 + 0.12, X1 = B.x1 - 0.12, Z0 = B.z0 + 0.12, Z1 = B.z1 - 0.12;

  // ---------- 地板 + 顶部灯箱 + 天花 ----------
  d.slab('glow', X1 - X0, Z1 - Z0, (X0 + X1) / 2, 0.03, (Z0 + Z1) / 2, '#d9d2c4');
  for (let i = 0; i < 6; i++) {
    const x = -3.5 + (i % 3) * 1.9, z = i < 3 ? -2.1 : -0.1;
    d.slab('glow', 1.35, 0.42, x, 3.12, z, '#fff6e2');
  }
  d.slab('body', X1 - X0, Z1 - Z0, (X0 + X1) / 2, 3.22, (Z0 + Z1) / 2, '#3b4250');
  // 地面导视：店门口到收银台的引导条 + 两块圆点贴
  d.slab('glow', 0.34, 2.6, 0.75, 0.05, -0.6, '#e8c85e');
  d.cyl('glow', 0.3, 0.3, 0.02, 12, 0.75, 0.05, 0.7, '#e8c85e');

  // ---------- 后墙饮料柜（四门柜 + 分层色带）+ 后场门 + 储物柜 ----------
  for (let i = 0; i < 4; i++) {
    const x = -3.45 + i * 1.05;
    d.box('glow', 0.98, 2.05, 0.5, x, 1.03, Z0 + 0.25, C.fridge);
    d.box('body', 1.02, 0.08, 0.54, x, 2.08, Z0 + 0.25, C.frame);
    for (let k = 0; k < 4; k++) {
      d.slab('body', 0.9, 0.46, x, 0.42 + k * 0.44, Z0 + 0.25, C.frame);
      for (let j = 0; j < 4; j++) d.box('glow', 0.18, 0.3, 0.1, x - 0.32 + j * 0.21, 0.62 + k * 0.44, Z0 + 0.24, PROD[(i + k + j) % 5]);
    }
  }
  d.box('body', 0.86, 2.15, 0.16, 1.15, 1.08, Z0 + 0.06, '#2b3240');            // 后场门
  d.box('glow', 0.1, 0.1, 0.3, 0.82, 1.05, Z0 + 0.2, C.warm);
  for (let i = 0; i < 3; i++) {                                                  // 储物柜一排
    d.box('glow', 0.34, 1.5, 0.42, -0.55 + i * 0.36, 0.75, Z0 + 0.2, i === 1 ? '#7fa9c9' : '#6f9bbd');
    d.box('body', 0.36, 0.05, 0.44, -0.55 + i * 0.36, 1.5, Z0 + 0.2, C.frame);
  }

  // ---------- 中岛货架（三排，垂直于橱窗 ⇒ 透过玻璃能看到往里延伸的纵深） ----------
  for (let r = 0; r < 3; r++) {
    const x = -2.9 + r * 1.25, len = 2.5, cz = -0.85;
    d.box('glow', 0.62, 0.16, len, x, 0.1, cz, '#cfc7b6');
    d.box('glow', 0.66, 1.62, 0.1, x, 0.9, cz + len / 2, '#e6ddc9');
    for (let k = 0; k < 3; k++) {
      const y = 0.55 + k * 0.46;
      d.box('glow', 0.6, 0.05, len, x, y, cz, '#efe6d2');
      for (let j = 0; j < 6; j++) {
        d.box('glow', 0.14, 0.28, 0.2, x - 0.2 + (j % 2) * 0.4, y + 0.17, cz - 1.0 + j * 0.4, PROD[(r + k + j) % 5]);
      }
    }
    d.box('body', 0.68, 1.7, 0.06, x, 0.9, cz - len / 2, C.frame);
  }
  // 货架端头的饭团堆（三棱柱 = 三段圆柱，白色海苔边）
  for (let r = 0; r < 3; r++) for (let i = 0; i < 3; i++) {
    d.cyl('glow', 0.15, 0.15, 0.12, 3, -2.9 + r * 1.25, 0.72 + i * 0.02, 0.55 - i * 0.02, i === 1 ? '#e9e3d2' : '#f4efe2', { rx: R90 });
  }

  // ---------- 便当区（东墙多层冷藏柜）+ 关东煮柜台（暖光锅） ----------
  for (let k = 0; k < 3; k++) {
    d.box('glow', 0.5, 0.12, 2.4, X1 - 0.32, 0.6 + k * 0.46, -1.0, '#dfe7ea');
    for (let j = 0; j < 5; j++) d.box('glow', 0.34, 0.14, 0.36, X1 - 0.32, 0.74 + k * 0.46, -2.0 + j * 0.5, PROD[(k + j) % 5]);
  }
  d.box('glass', 0.06, 1.5, 2.5, X1 - 0.06, 1.3, -1.0, C.glass);
  d.box('glow', 1.7, 0.86, 0.7, -3.3, 0.45, 0.35, '#e7dcc6');                   // 关东煮柜台体
  d.box('glow', 1.5, 0.1, 0.5, -3.3, 0.93, 0.35, C.oden);
  for (let i = 0; i < 4; i++) {
    d.cyl('glow', 0.17, 0.17, 0.16, 10, -3.85 + i * 0.37, 0.99, 0.35, ['#f0c27a', '#e8a05c', '#f5d9a8', '#d98a52'][i]);
  }
  d.box('body', 1.8, 0.08, 0.8, -3.3, 1.62, 0.35, C.frame);
  d.slab('glow', 1.6, 0.6, -3.3, 1.56, 0.35, C.warmMid);

  // ---------- 收银台 + POS + 咖啡机 + 糖果架 + 杂志架 ----------
  d.box('glow', 0.7, 0.92, 1.6, X1 - 0.45, 0.46, 0.15, '#e3d8c2');
  d.box('glow', 0.74, 0.08, 1.64, X1 - 0.45, 0.94, 0.15, '#c9bda6');
  d.box('body', 0.28, 0.34, 0.06, X1 - 0.6, 1.16, 0.5, C.frame);
  d.quad('glow', 0.24, 0.28, X1 - 0.44, 1.16, 0.5, '#8fd4ff', { ry: R90 });     // POS 屏
  d.box('body', 0.34, 0.5, 0.3, X1 - 0.5, 1.2, -0.45, '#3a4150');               // 咖啡机
  d.box('glow', 0.26, 0.12, 0.22, X1 - 0.5, 1.02, -0.45, C.warmMid);
  d.box('glow', 0.16, 0.34, 0.5, X1 - 0.5, 1.12, 0.9, '#f0e6d2');
  for (let i = 0; i < 4; i++) d.box('glow', 0.12, 0.12, 0.1, X1 - 0.28, 1.05 + i * 0.14, 0.9, PROD[i % 5]);
  d.box('glow', 0.5, 1.2, 0.12, 0.35, 0.62, 0.6, '#ded4bf');                    // 杂志架
  for (let i = 0; i < 4; i++) d.box('glow', 0.4, 0.3, 0.05, 0.35, 0.35 + i * 0.28, 0.66, PROD[(i + 2) % 5]);

  // ---------- 冰柜（西墙两只卧式玻璃盖）+ 墙面海报 ----------
  for (let i = 0; i < 2; i++) {
    const z = -2.0 + i * 1.5;
    d.box('glow', 0.66, 0.62, 1.3, X0 + 0.42, 0.33, z, '#e8eef2');
    d.box('glass', 0.6, 0.06, 1.2, X0 + 0.42, 0.66, z, C.glass);
    for (let j = 0; j < 3; j++) d.box('glow', 0.4, 0.16, 0.3, X0 + 0.42, 0.5, z - 0.4 + j * 0.4, PROD[(i + j) % 5]);
  }
  for (let i = 0; i < 3; i++) d.quad('glow', 0.5, 0.66, -1.2 + i * 0.75, 2.35, Z0 + 0.03, [C.neonB, C.warmMid, C.neonA][i]);
  d.quad('glow', 0.6, 0.8, X0 + 0.03, 1.9, -0.6, C.warm, { ry: R90 });
}
